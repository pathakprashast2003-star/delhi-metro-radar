-- =====================================================================
-- Delhi Metro Radar — live reports backend (Supabase / Postgres)
--
-- Design rules
--   * The browser timetable is always the fallback; this backend only
--     adds optional corrections on top. If it is down, the map still works.
--   * Clients never touch tables directly. They call two functions:
--       submit_report(...)   -> store one rider observation (validated)
--       get_live_state(line) -> combined recent observations + alerts
--   * Device identity = Supabase anonymous auth user (auth.uid()).
--     No names, emails or phone numbers are stored.
--   * Raw reports are deleted after 24 hours (purge_old_reports).
-- =====================================================================

-- ---------- Reference data ------------------------------------------------

create table if not exists public.lines (
  id    text primary key,          -- 'yellow'
  name  text not null
);

create table if not exists public.stations (
  line_id  text    not null references public.lines(id) on delete cascade,
  idx      integer not null,       -- order along the line, 0 = first terminal
  id       text    not null,       -- stable slug, e.g. 'rajiv_chowk'
  name     text    not null,
  primary key (line_id, idx),
  unique (line_id, id)
);

-- ---------- Raw reports ---------------------------------------------------

-- departed : a train just left this station in this direction
-- arrived  : a train just arrived at this station
-- stuck    : the rider's train has been stopped unusually long here
-- cleared  : the rider's train started moving again after being stuck
-- cell     : passive tower reading from the Android app (later)
do $$ begin
  create type public.report_kind as enum ('departed','arrived','stuck','cleared','cell');
exception when duplicate_object then null; end $$;

create table if not exists public.reports (
  id           uuid primary key,              -- generated by the client: resends are ignored
  device_id    uuid        not null,          -- auth.uid() of an anonymous session
  line_id      text        not null references public.lines(id),
  kind         public.report_kind not null,
  station_idx  integer     not null,
  direction    smallint    not null check (direction in (-1, 1)),  -- +1 = towards higher idx
  observed_at  timestamptz not null,          -- when it happened (phone clock, checked below)
  received_at  timestamptz not null default now(),
  cell_id      text,                          -- only for kind = 'cell'
  network      text,                          -- 'jio' | 'airtel' | 'vi' | ...
  foreign key (line_id, station_idx) references public.stations(line_id, idx)
);

create index if not exists reports_recent_idx
  on public.reports (line_id, observed_at desc);
create index if not exists reports_device_idx
  on public.reports (device_id, received_at desc);

-- ---------- Manual alerts (the delay banner) ------------------------------

create table if not exists public.alerts (
  id          bigint generated always as identity primary key,
  line_id     text        not null references public.lines(id),
  from_idx    integer     not null,
  to_idx      integer     not null,
  severity    text        not null check (severity in ('info','warning','severe')),
  message     text        not null check (length(message) between 3 and 280),
  active      boolean     not null default true,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null default now() + interval '3 hours'
);

-- Blocked devices (spam). Filled by hand or by a future abuse job.
create table if not exists public.blocked_devices (
  device_id   uuid primary key,
  reason      text,
  created_at  timestamptz not null default now()
);

-- ---------- Lock everything down ------------------------------------------
-- Row level security on, no policies for reports/alerts/blocked_devices:
-- the public API keys cannot read or write them directly. Only the
-- security-definer functions below (and the service role / dashboard) can.

alter table public.lines            enable row level security;
alter table public.stations         enable row level security;
alter table public.reports          enable row level security;
alter table public.alerts           enable row level security;
alter table public.blocked_devices  enable row level security;

drop policy if exists lines_read on public.lines;
create policy lines_read on public.lines for select using (true);
drop policy if exists stations_read on public.stations;
create policy stations_read on public.stations for select using (true);

-- ---------- Tunables ------------------------------------------------------

create or replace function public.cfg(key text) returns numeric
language sql immutable as $$
  select case key
    when 'max_past_s'        then 900   -- reject observations older than 15 min
    when 'max_future_s'      then 120   -- tolerate phone clocks up to 2 min fast
    when 'rate_window_s'     then 600   -- rate-limit window
    when 'rate_max'          then 30    -- max reports per device per window
    when 'repeat_window_s'   then 60    -- same device+station+kind within this = duplicate
    when 'live_window_s'     then 600   -- observations used for live state
    when 'decay_half_life_s' then 120   -- weight halves every 2 minutes
    when 'stuck_min_devices' then 3     -- devices needed before 'stuck' becomes a section alert
    when 'retention_h'       then 24
  end::numeric
$$;

-- ---------- submit_report -------------------------------------------------

create or replace function public.submit_report(
  p_id          uuid,
  p_line        text,
  p_kind        text,
  p_station     integer,
  p_direction   integer,
  p_observed_at timestamptz,
  p_cell_id     text default null,
  p_network     text default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_device uuid := auth.uid();
  v_kind   public.report_kind;
  v_now    timestamptz := now();
  v_recent integer;
begin
  -- identity: must be a signed-in (anonymous is fine) session
  if v_device is null then
    return jsonb_build_object('ok', false, 'status', 'unauthenticated');
  end if;

  if exists (select 1 from blocked_devices where device_id = v_device) then
    -- answer like success so spammers learn nothing
    return jsonb_build_object('ok', true, 'status', 'accepted');
  end if;

  if p_id is null then
    return jsonb_build_object('ok', false, 'status', 'missing_id');
  end if;

  begin
    v_kind := p_kind::public.report_kind;
  exception when invalid_text_representation then
    return jsonb_build_object('ok', false, 'status', 'bad_kind');
  end;

  if p_direction is null or p_direction not in (-1, 1) then
    return jsonb_build_object('ok', false, 'status', 'bad_direction');
  end if;

  if not exists (select 1 from stations where line_id = p_line and idx = p_station) then
    return jsonb_build_object('ok', false, 'status', 'bad_station');
  end if;

  if p_observed_at is null
     or p_observed_at < v_now - make_interval(secs => cfg('max_past_s'))
     or p_observed_at > v_now + make_interval(secs => cfg('max_future_s')) then
    return jsonb_build_object('ok', false, 'status', 'bad_time');
  end if;

  if v_kind = 'cell' and (p_cell_id is null or length(p_cell_id) > 64) then
    return jsonb_build_object('ok', false, 'status', 'bad_cell');
  end if;

  -- idempotency: the same report id sent twice (offline queue resend) is ignored
  if exists (select 1 from reports where id = p_id) then
    return jsonb_build_object('ok', true, 'status', 'duplicate');
  end if;

  -- rate limit per device
  select count(*) into v_recent
  from reports
  where device_id = v_device
    and received_at > v_now - make_interval(secs => cfg('rate_window_s'));
  if v_recent >= cfg('rate_max') then
    return jsonb_build_object('ok', false, 'status', 'rate_limited');
  end if;

  -- double taps: same device, station, kind, direction within a minute
  if v_kind <> 'cell' and exists (
      select 1 from reports
      where device_id = v_device and line_id = p_line
        and station_idx = p_station and kind = v_kind and direction = p_direction
        and abs(extract(epoch from (observed_at - p_observed_at))) < cfg('repeat_window_s')) then
    return jsonb_build_object('ok', true, 'status', 'duplicate');
  end if;

  insert into reports (id, device_id, line_id, kind, station_idx, direction,
                       observed_at, cell_id, network)
  values (p_id, v_device, p_line, v_kind, p_station, p_direction::smallint,
          least(p_observed_at, v_now), p_cell_id, lower(p_network))
  on conflict (id) do nothing;

  return jsonb_build_object('ok', true, 'status', 'accepted');
end;
$$;

-- ---------- get_live_state ------------------------------------------------
-- Combines recent observations. Each device counts once per
-- (station, direction, kind) using its latest report; weight decays with age.
-- The browser matches 'departed'/'arrived' observations to the nearest
-- scheduled train and shifts it; 'stuck' groups become section warnings.

create or replace function public.get_live_state(p_line text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  with params as (
    select now() as t,
           cfg('live_window_s')     as win,
           cfg('decay_half_life_s') as half,
           cfg('stuck_min_devices') as stuck_min
  ),
  latest as (   -- one row per device per (station, direction, kind)
    select distinct on (r.device_id, r.station_idx, r.direction, r.kind)
           r.device_id, r.station_idx, r.direction, r.kind, r.observed_at
    from reports r, params p
    where r.line_id = p_line
      and r.kind in ('departed','arrived','stuck','cleared')
      and r.observed_at > p.t - make_interval(secs => p.win)
      and r.device_id not in (select device_id from blocked_devices)
    order by r.device_id, r.station_idx, r.direction, r.kind, r.observed_at desc
  ),
  grouped as (
    select l.station_idx, l.direction, l.kind,
           count(*)                                   as devices,
           max(l.observed_at)                         as last_observed_at,
           -- median observation time is robust to one wrong phone clock
           to_timestamp(percentile_cont(0.5) within group
                        (order by extract(epoch from l.observed_at))) as typical_observed_at,
           sum(power(0.5, extract(epoch from (p.t - l.observed_at)) / p.half)) as score
    from latest l, params p
    group by l.station_idx, l.direction, l.kind
  ),
  observations as (
    select coalesce(jsonb_agg(jsonb_build_object(
             'station_idx', g.station_idx,
             'direction',   g.direction,
             'kind',        g.kind,
             'devices',     g.devices,
             'observed_at', g.typical_observed_at,
             'last_observed_at', g.last_observed_at,
             'score',       round(g.score::numeric, 3),
             'confidence',  case when g.devices >= 3 and g.score >= 1.5 then 'high'
                                 when g.devices >= 2 and g.score >= 0.8 then 'medium'
                                 else 'low' end)
           order by g.station_idx, g.direction, g.kind), '[]'::jsonb) as j
    from grouped g
    where g.kind in ('departed','arrived')
  ),
  stuck as (    -- stuck minus cleared, per station/direction
    select s.station_idx, s.direction, s.devices, s.last_observed_at
    from grouped s, params p
    where s.kind = 'stuck'
      and s.devices >= p.stuck_min
      and not exists (
        select 1 from grouped c
        where c.kind = 'cleared' and c.station_idx = s.station_idx
          and c.direction = s.direction
          and c.last_observed_at > s.last_observed_at
          and c.devices >= 2)
  ),
  community_alerts as (
    select coalesce(jsonb_agg(jsonb_build_object(
             'source',      'riders',
             'station_idx', st.station_idx,
             'direction',   st.direction,
             'devices',     st.devices,
             'since',       st.last_observed_at,
             'message',     'Riders report a train held at ' || s.name)
           order by st.station_idx), '[]'::jsonb) as j
    from stuck st
    join stations s on s.line_id = p_line and s.idx = st.station_idx
  ),
  manual_alerts as (
    select coalesce(jsonb_agg(jsonb_build_object(
             'source',   'admin',
             'from_idx', a.from_idx,
             'to_idx',   a.to_idx,
             'severity', a.severity,
             'message',  a.message,
             'since',    a.created_at)
           order by a.created_at desc), '[]'::jsonb) as j
    from alerts a, params p
    where a.line_id = p_line and a.active and a.expires_at > p.t
  )
  select jsonb_build_object(
    'line',         p_line,
    'server_time',  (select t from params),
    'window_s',     (select win from params),
    'observations', (select j from observations),
    'alerts',       (select j from manual_alerts) || (select j from community_alerts)
  );
$$;

-- ---------- Retention -----------------------------------------------------

create or replace function public.purge_old_reports()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare n integer;
begin
  delete from reports where received_at < now() - make_interval(hours => cfg('retention_h')::int);
  get diagnostics n = row_count;
  update alerts set active = false where active and expires_at < now();
  return n;
end;
$$;

-- Schedule hourly purge if pg_cron is enabled (Supabase: Database -> Extensions -> pg_cron).
do $$ begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('purge-old-reports', '7 * * * *', 'select public.purge_old_reports()');
  end if;
end $$;

-- ---------- Who may call what ---------------------------------------------

revoke all on function public.submit_report(uuid,text,text,integer,integer,timestamptz,text,text) from public;
revoke all on function public.get_live_state(text) from public;
revoke all on function public.purge_old_reports() from public;

do $$ begin
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    grant execute on function public.submit_report(uuid,text,text,integer,integer,timestamptz,text,text) to authenticated;
    grant execute on function public.get_live_state(text) to authenticated;
  end if;
  if exists (select 1 from pg_roles where rolname = 'anon') then
    grant execute on function public.get_live_state(text) to anon;   -- reading needs no session
  end if;
end $$;
